BEGIN;

-- Nuevos roles institucionales.
INSERT INTO roles (id_rol,nombre_rol) VALUES
(7,'biblioteca'),
(8,'laboratorios'),
(9,'centro_idiomas')
ON CONFLICT (id_rol) DO UPDATE SET nombre_rol=EXCLUDED.nombre_rol;

-- Validaciones encadenadas para cierre de estadia.
CREATE TABLE IF NOT EXISTS validaciones_cierre_estadia (
  id_validacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estadia INTEGER NOT NULL REFERENCES estadias(id_estadia) ON DELETE CASCADE,
  area VARCHAR(40) NOT NULL CHECK (area IN ('biblioteca','laboratorios','centro_idiomas','servicios_escolares','empresa_memoria')),
  estado VARCHAR(30) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','en_revision','aprobado','rechazado','requiere_correccion')),
  ruta_archivo TEXT,
  nombre_archivo VARCHAR(255),
  mime_type VARCHAR(120),
  observaciones TEXT,
  token_publico VARCHAR(96),
  enviado_en TIMESTAMP,
  revisado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  revisado_en TIMESTAMP,
  actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(id_estadia,area)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_validacion_token_publico
  ON validaciones_cierre_estadia(token_publico)
  WHERE token_publico IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_validaciones_cierre_area_estado
  ON validaciones_cierre_estadia(area,estado);

-- Toma de protesta: una por estadia.
CREATE TABLE IF NOT EXISTS tomas_protesta (
  id_toma INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estadia INTEGER NOT NULL UNIQUE REFERENCES estadias(id_estadia) ON DELETE CASCADE,
  fecha_hora TIMESTAMP NOT NULL,
  lugar VARCHAR(180),
  observaciones TEXT,
  estado VARCHAR(30) NOT NULL DEFAULT 'programada' CHECK (estado IN ('programada','en_evaluacion','aprobada','requiere_revision','cancelada')),
  creada_por INTEGER NOT NULL REFERENCES profesores(id_profesor),
  creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finalizada_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS toma_protesta_evaluadores (
  id_toma INTEGER NOT NULL REFERENCES tomas_protesta(id_toma) ON DELETE CASCADE,
  id_profesor INTEGER NOT NULL REFERENCES profesores(id_profesor),
  orden INTEGER NOT NULL CHECK (orden IN (1,2)),
  asignado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(id_toma,id_profesor),
  UNIQUE(id_toma,orden)
);

CREATE TABLE IF NOT EXISTS evaluaciones_toma_protesta (
  id_evaluacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_toma INTEGER NOT NULL REFERENCES tomas_protesta(id_toma) ON DELETE CASCADE,
  id_profesor INTEGER NOT NULL REFERENCES profesores(id_profesor),
  codigo_nivel VARCHAR(4) NOT NULL,
  calificacion NUMERIC(5,2) NOT NULL,
  observaciones TEXT,
  evaluado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(id_toma,id_profesor)
);

CREATE INDEX IF NOT EXISTS idx_tomas_protesta_fecha ON tomas_protesta(fecha_hora);

-- Estado final de la estadia y control del cierre.
ALTER TABLE estadias ADD COLUMN IF NOT EXISTS cierre_solicitado_en TIMESTAMP;
ALTER TABLE estadias ADD COLUMN IF NOT EXISTS cierre_completado_en TIMESTAMP;
ALTER TABLE estadias ADD COLUMN IF NOT EXISTS toma_protesta_aprobada BOOLEAN NOT NULL DEFAULT FALSE;

COMMIT;
SELECT 'Migracion 17 aplicada. SkillMatch V8 cierre institucional listo.' AS resultado;
