-- 3) Comprobantes previos: cuatrimestre, seguro e inscripcion.
CREATE TABLE IF NOT EXISTS comprobantes_inicio_estadia (
  id_comprobante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estadia INTEGER NOT NULL REFERENCES estadias(id_estadia) ON DELETE CASCADE,
  tipo VARCHAR(40) NOT NULL CHECK(tipo IN ('cuatrimestre','seguro_facultativo','inscripcion')),
  numero_seguro VARCHAR(80),
  ruta_archivo TEXT NOT NULL,
  nombre_archivo VARCHAR(255),
  mime_type VARCHAR(120),
  estado VARCHAR(30) NOT NULL DEFAULT 'en_revision' CHECK(estado IN ('pendiente','en_revision','aprobado','rechazado','requiere_correccion')),
  observaciones TEXT,
  enviado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revisado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  revisado_en TIMESTAMP,
  UNIQUE(id_estadia,tipo)
);
CREATE INDEX IF NOT EXISTS idx_comprobantes_inicio_estado ON comprobantes_inicio_estadia(tipo,estado);

-- 4) Documentos oficiales: se conserva el generado y el firmado.
CREATE TABLE IF NOT EXISTS documentos_oficiales_estadia (
  id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estadia INTEGER NOT NULL REFERENCES estadias(id_estadia) ON DELETE CASCADE,
  tipo VARCHAR(50) NOT NULL CHECK(tipo IN ('carta_inicio','carta_finalizacion','autorizacion_memoria','acta_toma_protesta','acta_final')),
  estado VARCHAR(30) NOT NULL DEFAULT 'no_generado' CHECK(estado IN ('no_generado','generado','firmado_en_revision','firmado_validado','rechazado')),
  ruta_generado TEXT,
  generado_en TIMESTAMP,
  generado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  ruta_firmado TEXT,
  nombre_firmado VARCHAR(255),
  mime_firmado VARCHAR(120),
  firmado_subido_en TIMESTAMP,
  firmado_subido_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  firmado_validado_por INTEGER REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  firmado_validado_en TIMESTAMP,
  observaciones TEXT,
  UNIQUE(id_estadia,tipo)
);

-- 5) Extiende el tablero institucional con los pasos oficiales restantes.
