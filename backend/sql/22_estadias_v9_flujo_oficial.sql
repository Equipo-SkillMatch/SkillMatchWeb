-- 6) Preparacion para correos: solo eventos, no se envia nada todavia.
CREATE TABLE IF NOT EXISTS eventos_notificacion_estadia (
  id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estadia INTEGER REFERENCES estadias(id_estadia) ON DELETE CASCADE,
  tipo VARCHAR(80) NOT NULL,
  destinatarios TEXT,
  asunto VARCHAR(255),
  contexto JSONB NOT NULL DEFAULT '{}'::jsonb,
  estado VARCHAR(30) NOT NULL DEFAULT 'pendiente_configuracion' CHECK(estado IN ('pendiente_configuracion','listo','enviado','error')),
  creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  enviado_en TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_eventos_notificacion_estadia ON eventos_notificacion_estadia(id_estadia,tipo,estado);

